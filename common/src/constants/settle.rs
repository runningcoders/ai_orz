//! 记忆沉淀（settle）的队列护栏常量
//!
//! 这个数字有两类读者、方向相反：运行时域用它当取数硬护栏（一次最多取多少条
//! 待沉淀记忆），系统域用它当 cron payload 的默认 `settle_limit`。任何一侧
//! 直接引用另一侧都是域间调用，因此下沉到 `common`（依赖链最底端）。
//!
//! ⚠️ 只有一处的常量才不会被改漏：新增消费方请直接引用本模块，不要复制数值。

/// 单批待沉淀记忆的条数上限（防呆，避免极端情况下无限拼接）
///
/// ⚠️ 这是**硬护栏**不是批量策略：真正的批量由上下文预算决定
/// （见 runtime `legacy_settle::pending` 的批量策略说明）。
pub const PENDING_MAX_ITEMS: usize = 200;
