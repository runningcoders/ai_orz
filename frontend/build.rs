//! Frontend build script
//!
//! Read backend configuration at compile time and embed it into frontend binary.
//! This ensures frontend and backend share the same configuration.

use common::config::AppConfig;
use std::fs;
use std::path::Path;
use std::process::Command;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=../.ai_orz/ai_orz.toml");
    println!("cargo:rerun-if-changed=../common/config/ai_orz.toml");
    println!("cargo:rerun-if-changed=styles/input.css");
    println!("cargo:rerun-if-changed=package.json");
    println!("cargo:rerun-if-changed=package-lock.json");

    compile_tailwind()?;
    copy_docs()?;

    let config_path = Path::new("../.ai_orz/ai_orz.toml");

    let config_content = if config_path.exists() {
        fs::read_to_string(config_path)?
    } else {
        let default_config = include_str!("../common/config/ai_orz.toml");
        default_config.to_string()
    };

    let config: AppConfig = toml::from_str(&config_content)?;

    let config_json = serde_json::to_string_pretty(&config)?;

    let generated_code = format!(
        "// Generated compile-time configuration from build.rs\n\
        // DO NOT EDIT - This file is automatically generated by build.rs\n\n\
        use common::config::AppConfig;\n\n\
        /// Static configuration embedded at compile time from backend config file\n\
        pub static COMPILED_CONFIG: &str = r###\"{config_json}\"###;\n\n\
        /// Get the parsed configuration at runtime\n\
        pub fn get_config() -> AppConfig {{\n\
            serde_json::from_str(COMPILED_CONFIG).expect(\"Failed to parse compiled config\")\n\
        }}\n"
    );

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let out_path = Path::new(&out_dir).join("compiled_config.rs");
    fs::write(out_path, generated_code)?;

    Ok(())
}

/// 确定性短 ID：基于路径字符串的 128-bit 哈希
/// 将任意长路径映射为固定长度的十六进制字符串，避免文件系统路径超长（>256 字符）
fn short_id(rel: &str) -> String {
    let mut h: u128 = 5381;
    for b in rel.bytes() {
        h = h.wrapping_mul(31).wrapping_add(b as u128);
    }
    format!("{:032x}", h)
}

/// 读取 HTML 文档 `<title>` 作为目录展示标题（失败时由调用方回退文件名）
fn html_title(path: &Path) -> Option<String> {
    let bytes = fs::read(path).ok()?;
    let content = String::from_utf8_lossy(&bytes);
    let start = content.find("<title>")? + "<title>".len();
    let rest = &content[start..];
    let end = rest.find("</title>")?;
    let title = rest[..end].trim();
    if title.is_empty() {
        None
    } else {
        Some(title.to_string())
    }
}

/// 从 Markdown 提取展示标题：YAML frontmatter 的 `title:` → 首个 H1 → 调用方回退文件名。
///
/// 本项目文档也用 `---` 作水平分隔线，因此 frontmatter 必须同时满足
/// 「首行 `---` + 有闭合 `---` + 中间出现合法键」才认定，避免误吞正文。
fn md_title(path: &Path) -> Option<String> {
    let bytes = fs::read(path).ok()?;
    let content = String::from_utf8_lossy(&bytes);

    if let Some(body) = content
        .strip_prefix("---\n")
        .or_else(|| content.strip_prefix("---\r\n"))
        && let Some(end) = body.find("\n---")
    {
        let frontmatter = &body[..end];
        let looks_like_frontmatter = ["title:", "kind:", "name:", "module:"]
            .iter()
            .any(|key| frontmatter.contains(key));
        if looks_like_frontmatter {
            let title = frontmatter
                .lines()
                .filter_map(|line| line.trim().strip_prefix("title:"))
                .map(|value| value.trim().trim_matches(|c| c == '"' || c == '\''))
                .find(|value| !value.is_empty());
            if let Some(title) = title {
                return Some(title.to_string());
            }
        }
    }

    content.lines().find_map(|line| {
        let heading = line
            .trim()
            .strip_prefix("# ")?
            .trim()
            .trim_matches('*')
            .trim();
        (!heading.is_empty()).then(|| heading.to_string())
    })
}

/// 层级目录树节点
enum DocNode {
    File {
        /// 展示标题（frontmatter title / H1 / 文件名）
        title: String,
        /// 文件 stem，仅用于识别「同名目录包同名文件」
        name: String,
        /// 站内副本路径（`modules/{hash}.md`）
        short_path: String,
        /// 原始仓库相对路径（`docs/modules/<模块>/.../<文件>.md`），渲染期归一化 `./` 链接用
        repo_path: String,
        /// 空串表示 Markdown；`html` 表示自包含 HTML（前端右侧 iframe 内嵌）
        kind: String,
    },
    Dir {
        name: String,
        children: Vec<DocNode>,
    },
}

/// 复制单个文档文件（`.md` / `.html`）为 `{dest_prefix}/{hash}.{ext}`（哈希短路径）
/// 并生成目录节点。
///
/// 其他扩展名返回 `None`；`base` 为仓库内相对路径的基准（通常是 `docs/`）。
fn copy_doc_node(
    path: &Path,
    base: &Path,
    dest_root: &Path,
    dest_prefix: &str,
) -> std::io::Result<Option<DocNode>> {
    let Some(ext) = path.extension().and_then(|e| e.to_str()) else {
        return Ok(None);
    };
    if !matches!(ext, "md" | "html") {
        return Ok(None);
    }
    let Ok(rel) = path.strip_prefix(base) else {
        return Ok(None);
    };
    let rel_str = rel.to_string_lossy().replace('\\', "/");
    let short_path = format!("{}/{}.{}", dest_prefix, short_id(&rel_str), ext);
    let dest = dest_root.join(&short_path);
    if let Some(parent) = dest.parent() {
        let _ = fs::create_dir_all(parent);
    }
    // 原样复制字节：`./` `../` 的归一化放到渲染期做（需要原文位置，
    // 由 index.json 的 repo_path 提供），打包期不改文档内容。
    let repo_path = format!("docs/{rel_str}");
    fs::copy(path, &dest)?;
    println!("cargo:rerun-if-changed={}", path.display());
    let name = Path::new(&rel_str)
        .file_stem()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_else(|| rel_str.clone());
    let title = if ext == "html" {
        html_title(path).unwrap_or_else(|| name.clone())
    } else {
        md_title(path).unwrap_or_else(|| name.clone())
    };
    Ok(Some(DocNode::File {
        title,
        name,
        short_path,
        repo_path,
        kind: if ext == "html" {
            "html".to_string()
        } else {
            String::new()
        },
    }))
}

/// 递归遍历目录 → 目录树；文档文件一律复制为 `{dest_prefix}/{hash}.{ext}`（哈希短路径）。
///
/// 只扁平化「同名目录包同名文件」（`卡名/卡名.md`），其余目录保留为分组——
/// 目录名是位置信息（如 `架构设计/领域层.md`），丢了读者就分不清文档归属。
/// 同时收录 `.md` 与自包含 `.html`（如设计原型），两者都走前端统一文档加载。
fn walk_dir_hierarchical(
    dir: &Path,
    base: &Path,
    dest_root: &Path,
    dest_prefix: &str,
) -> std::io::Result<Vec<DocNode>> {
    let mut nodes = Vec::new();
    let mut paths: Vec<std::path::PathBuf> = fs::read_dir(dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            let dir_name = path
                .file_name()
                .map(|s| s.to_string_lossy().to_string())
                .unwrap_or_default();
            let children = walk_dir_hierarchical(&path, base, dest_root, dest_prefix)?;
            if children.is_empty() {
                continue;
            }
            let is_same_name_package = children.len() == 1
                && matches!(&children[0], DocNode::File { name, .. } if *name == dir_name);
            if is_same_name_package {
                nodes.extend(children);
            } else {
                nodes.push(DocNode::Dir {
                    name: dir_name,
                    children,
                });
            }
        } else if path
            .extension()
            .is_some_and(|ext| ext == "md" || ext == "html")
            && let Some(node) = copy_doc_node(&path, base, dest_root, dest_prefix)?
        {
            nodes.push(node);
        }
    }
    Ok(nodes)
}

fn node_to_json(node: &DocNode) -> serde_json::Value {
    match node {
        DocNode::File {
            title,
            short_path,
            repo_path,
            kind,
            ..
        } => {
            if kind.is_empty() {
                serde_json::json!({ "title": title, "path": short_path, "repo_path": repo_path })
            } else {
                serde_json::json!({
                    "title": title,
                    "path": short_path,
                    "repo_path": repo_path,
                    "type": kind
                })
            }
        }
        DocNode::Dir { name, children } => {
            let children_json: Vec<serde_json::Value> = children.iter().map(node_to_json).collect();
            serde_json::json!({ "label": name, "children": children_json })
        }
    }
}

/// 文档中心静态资源：将仓库 docs/ 中的核心文档复制到 public/docs/，
/// 并生成目录清单 index.json 供前端文档中心页面运行时 fetch。
///
/// 所有文档文件统一使用 [`short_id`] 生成的哈希短路径存储，
/// 避免深嵌套目录名导致的路径超长问题。
/// 原始标题和目录结构仅用于前端 UI 展示。
///
/// 复制时**不改文档内容**：每条文档在 index.json 里带上原始 `repo_path`，
/// 渲染期据此归一化 `./` `../` 链接并决定站内打开还是跳 GitHub。
///
/// 收录范围（docs/ 下**全部**文档，保证站内互链不退化到 GitHub）：
/// - docs/ 根目录的纲要文档（路径短，保留原名）
/// - docs/modules/<模块>/{A-设计,B-落地方案,C-知识}/（能力域知识库，三层结构保留）
/// - docs/modules/INDEX.md 与各模块 `00-INDEX.md`（自动生成索引，单独分区）
/// - docs/diagrams/（图表 HTML 直出 + README 说明）
fn copy_docs() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let docs_src = Path::new(&manifest_dir).join("../docs");
    if !docs_src.exists() {
        println!("cargo:warning=docs/ not found, skipping docs center copy");
        return Ok(());
    }

    let dest_root = Path::new(&manifest_dir).join("public/docs");
    if dest_root.exists() {
        fs::remove_dir_all(&dest_root)?;
    }
    fs::create_dir_all(&dest_root)?;

    let mut sections: Vec<serde_json::Value> = Vec::new();

    // ---- 分区 1：总览（根目录纲要文档，路径短无需哈希）----
    {
        let root_docs: &[(&str, &str)] = &[
            ("README.md", "知识库使用指南"),
            ("ARCHITECTURE.md", "架构总纲"),
            ("CODE_STANDARDS.md", "编码规范"),
            ("LAYERED_ARCHITECTURE_PRACTICE.md", "分层架构实践"),
            ("AGENT_GUIDE.md", "Agent 实现指引"),
            ("DOCUMENTATION.md", "文档维护规范"),
            ("memory_design.md", "记忆系统设计"),
            (
                "ARCHITECTURE_STATUS_20260725.md",
                "分层架构现状（2026-07-25）",
            ),
            (
                "DOCUMENTATION_REORG_PLAN.md",
                "文档规范与仓库精简（2026-08-15）",
            ),
            ("CODE_WIKI.md", "Code Wiki 入口"),
            ("wiki-maintenance.md", "Wiki 维护说明"),
        ];
        let mut overview_docs: Vec<serde_json::Value> = Vec::new();
        for (file, title) in root_docs {
            let src = docs_src.join(file);
            if src.exists() {
                // 原样复制 + 记录原始仓库路径：根纲要的 `./modules/INDEX.md` 以
                // `docs/<file>` 为基准，归一化留给渲染期，避免打包期改内容
                let repo_path = format!("docs/{file}");
                fs::copy(&src, dest_root.join(file))?;
                println!("cargo:rerun-if-changed={}", src.display());
                overview_docs.push(
                    serde_json::json!({ "title": title, "path": file, "repo_path": repo_path }),
                );
            }
        }
        if !overview_docs.is_empty() {
            sections.push(serde_json::json!({ "label": "总览", "docs": overview_docs }));
        }
    }

    // ---- 分区 2：能力域知识库（docs/modules/<模块>/{A-设计,B-落地方案,C-知识}/）----
    // 三层结构固定保留（模块 → 层 → 文档），层内的「同名目录包同名文件」由 walk 扁平化。
    {
        let modules_src = docs_src.join("modules");
        if modules_src.is_dir() {
            // 监听目录本身：新增/删除模块时也要重新构建
            println!("cargo:rerun-if-changed={}", modules_src.display());
            let mut module_dirs: Vec<std::path::PathBuf> = fs::read_dir(&modules_src)?
                .filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|path| path.is_dir())
                .collect();
            module_dirs.sort();

            let mut module_groups: Vec<serde_json::Value> = Vec::new();
            for module_dir in module_dirs {
                let Some(module_name) = module_dir
                    .file_name()
                    .map(|name| name.to_string_lossy().to_string())
                else {
                    continue;
                };

                let mut tiers: Vec<serde_json::Value> = Vec::new();
                for tier in ["A-设计", "B-落地方案", "C-知识"] {
                    let tier_dir = module_dir.join(tier);
                    if !tier_dir.is_dir() {
                        continue;
                    }
                    let tree = walk_dir_hierarchical(&tier_dir, &docs_src, &dest_root, "modules")?;
                    if tree.is_empty() {
                        continue;
                    }
                    let children: Vec<serde_json::Value> = tree.iter().map(node_to_json).collect();
                    tiers.push(serde_json::json!({ "label": tier, "children": children }));
                }

                if !tiers.is_empty() {
                    module_groups
                        .push(serde_json::json!({ "label": module_name, "children": tiers }));
                }
            }

            if !module_groups.is_empty() {
                sections
                    .push(serde_json::json!({ "label": "能力域知识库", "groups": module_groups }));
            }
        }
    }

    // ---- 分区 4：图表资源（docs/diagrams/ 下的 .html，保留原相对路径直出）----
    // 图表是自包含 HTML，前端无法按 Markdown 渲染：保留 diagrams/xxx.html 原路径，
    // 由文档中心右侧 iframe 内嵌加载（也可 /docs/diagrams/xxx.html 新标签直开，
    // 见 pages/system/docs.rs）。
    let mut diagrams_section: Option<serde_json::Value> = None;
    {
        let diagrams_src = docs_src.join("diagrams");
        if diagrams_src.is_dir() {
            // 监听目录本身，新增/删除图表文件时可触发重新构建
            println!("cargo:rerun-if-changed={}", diagrams_src.display());
            let mut html_files: Vec<std::path::PathBuf> = Vec::new();
            let mut stack = vec![diagrams_src.clone()];
            while let Some(current) = stack.pop() {
                for entry in fs::read_dir(&current)? {
                    let path = entry?.path();
                    if path.is_dir() {
                        stack.push(path);
                    } else if path.extension().is_some_and(|ext| ext == "html") {
                        html_files.push(path);
                    }
                }
            }
            html_files.sort();
            let mut diagrams: Vec<serde_json::Value> = Vec::new();
            for path in html_files {
                let Ok(rel) = path.strip_prefix(&docs_src) else {
                    continue;
                };
                let rel_str = rel.to_string_lossy().replace('\\', "/");
                let dest = dest_root.join(&rel_str);
                if let Some(parent) = dest.parent() {
                    let _ = fs::create_dir_all(parent);
                }
                fs::copy(&path, &dest)?;
                println!("cargo:rerun-if-changed={}", path.display());
                let title = html_title(&path).unwrap_or_else(|| {
                    Path::new(&rel_str)
                        .file_stem()
                        .map(|s| s.to_string_lossy().to_string())
                        .unwrap_or_else(|| rel_str.clone())
                });
                diagrams.push(serde_json::json!({
                    "title": title,
                    "path": rel_str,
                    // 原始仓库路径：文档中心用它写深链（#doc=）并定位左侧导航
                    "repo_path": format!("docs/{rel_str}"),
                    "type": "html"
                }));
            }
            // 目录说明 README（Markdown）与图表一起收录，避免文档内引用退化为 GitHub
            let readme_src = diagrams_src.join("README.md");
            if readme_src.exists()
                && let Some(node) = copy_doc_node(&readme_src, &docs_src, &dest_root, "diagrams")?
            {
                diagrams.insert(0, node_to_json(&node));
            }
            if !diagrams.is_empty() {
                diagrams_section = Some(serde_json::json!({ "label": "架构图", "docs": diagrams }));
            }
        }
    }

    // 「架构图」分区固定在总览之后展示（无总览时置顶），保证文档中心首屏可见
    if let Some(section) = diagrams_section {
        let pos = sections.len().min(1);
        sections.insert(pos, section);
    }

    // ---- 分区 3：模块索引（modules/INDEX.md + 各模块 00-INDEX.md）----
    // 总览类文档（docs/README.md 等）大量引用这些自动生成索引；
    // 收录后站内点击不再退化到 GitHub。
    {
        let modules_src = docs_src.join("modules");
        if modules_src.is_dir() {
            let mut index_docs: Vec<serde_json::Value> = Vec::new();
            let top_index = modules_src.join("INDEX.md");
            if top_index.exists()
                && let Some(node) =
                    copy_doc_node(&top_index, &docs_src, &dest_root, "modules-index")?
            {
                index_docs.push(node_to_json(&node));
            }
            let mut module_dirs: Vec<std::path::PathBuf> = fs::read_dir(&modules_src)?
                .filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|path| path.is_dir())
                .collect();
            module_dirs.sort();
            for module_dir in module_dirs {
                let index_src = module_dir.join("00-INDEX.md");
                if index_src.exists()
                    && let Some(node) =
                        copy_doc_node(&index_src, &docs_src, &dest_root, "modules-index")?
                {
                    index_docs.push(node_to_json(&node));
                }
            }
            if !index_docs.is_empty() {
                sections.push(serde_json::json!({ "label": "模块索引", "docs": index_docs }));
            }
        }
    }

    let index = serde_json::json!({ "sections": sections });
    let index_json = serde_json::to_string_pretty(&index)?;
    fs::write(dest_root.join("index.json"), index_json)?;

    Ok(())
}

fn compile_tailwind() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let input = Path::new(&manifest_dir).join("styles/input.css");
    let output = Path::new(&manifest_dir).join("public/output.css");
    let node_modules_bin = Path::new(&manifest_dir).join("node_modules/.bin/tailwindcss");
    let node_modules_dir = Path::new(&manifest_dir).join("node_modules");

    if !input.exists() {
        return Ok(());
    }

    fs::create_dir_all(Path::new(&manifest_dir).join("public"))?;

    if !node_modules_bin.exists() {
        if node_modules_dir.exists() {
            println!(
                "cargo:warning=node_modules exists but tailwindcss binary not found, trying npm install..."
            );
        } else {
            println!("cargo:warning=node_modules not found, running npm install...");
        }
        let npm_status = Command::new("npm")
            .arg("install")
            .current_dir(&manifest_dir)
            .status();
        match npm_status {
            Ok(s) if s.success() => {}
            Ok(s) => {
                println!(
                    "cargo:warning=npm install failed with status: {}, skipping CSS build",
                    s
                );
                return Ok(());
            }
            Err(e) => {
                println!("cargo:warning=npm not found ({}), skipping CSS build", e);
                return Ok(());
            }
        }
    }

    if !node_modules_bin.exists() {
        println!(
            "cargo:warning=tailwindcss binary still not found after npm install, skipping CSS build"
        );
        return Ok(());
    }

    let status = Command::new(&node_modules_bin)
        .arg("-i")
        .arg(&input)
        .arg("-o")
        .arg(&output)
        .arg("--minify")
        .current_dir(&manifest_dir)
        .status();

    match status {
        Ok(s) if s.success() => {
            println!("cargo:warning=Tailwind CSS compiled successfully");
        }
        Ok(s) => {
            println!(
                "cargo:warning=Tailwind CSS compilation exited with status: {}",
                s
            );
        }
        Err(e) => {
            println!("cargo:warning=Failed to run tailwindcss: {}", e);
        }
    }

    Ok(())
}
